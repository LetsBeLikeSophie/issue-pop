def classify_category(cluster_articles: list[dict]) -> str:
    """클러스터 하나에 카테고리 라벨(정치/경제/사회/국제/스포츠/연예/IT과학/기타)을 붙여요.

    클러스터 안 모든 기사의 제목+요약에서 명사를 뽑아 카테고리별 키워드
    사전과 몇 개나 겹치는지 세고, 제일 많이 겹치는 카테고리를 고름.
    아무 카테고리와도 안 겹치면(사전에 없는 신조어/고유명사뿐인 경우)
    "기타"로 분류.
    """
    tokens: Counter = Counter()
    for a in cluster_articles:
        title = clean_title(a["title"])
        summary = clean_summary(a.get("summary", ""))
        for t in extract_nouns(f"{title} {summary}"):
            tokens[t.lower()] += 1

    if not tokens:
        return "기타"

    scores = {}
    for category, keywords in CATEGORY_KEYWORDS.items():
        score = sum(count for tok, count in tokens.items() if tok in keywords)
        if score:
            scores[category] = score

    if not scores:
        return "기타"

    # 동점이면 카테고리 딕셔너리 정의 순서(정치가 제일 앞)로 결정론적으로 고름.
    best = max(scores.items(), key=lambda kv: (kv[1], -list(CATEGORY_KEYWORDS).index(kv[0])))
    return best[0]
